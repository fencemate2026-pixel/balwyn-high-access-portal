-- ============================================================================
-- Staff time-on-portal and button-press record (15 Oct 2026).
--
-- staff_presence : one row per browser session. active_seconds is accumulated
--                  by the SERVER from the gaps between heartbeats (a gap over
--                  90 s counts as idle), so a browser cannot claim more time
--                  than the wall clock allows.
-- staff_ui_events: what the person pressed (button / link / tab LABEL only).
--                  No typed text, no passwords, no field values are recorded.
--
-- Both tables are written only by the portal server (balwyn_app) and read only
-- through the administrator-only /api/accounts routes. Kept 12 months, then
-- deleted by the portal when a new session starts.
-- ============================================================================
CREATE TABLE IF NOT EXISTS balwyn_portal.staff_presence (
  session_id      uuid PRIMARY KEY,
  account_key     text NOT NULL CHECK (char_length(account_key) BETWEEN 1 AND 254),
  actor_name      text NOT NULL CHECK (char_length(actor_name) BETWEEN 1 AND 200),
  actor_role      text NOT NULL CHECK (actor_role IN ('viewer', 'operator', 'administrator')),
  started_at      timestamptz NOT NULL DEFAULT now(),
  last_seen_at    timestamptz NOT NULL DEFAULT now(),
  active_seconds  integer NOT NULL DEFAULT 0 CHECK (active_seconds BETWEEN 0 AND 86400)
);
CREATE INDEX IF NOT EXISTS idx_staff_presence_account ON balwyn_portal.staff_presence (account_key, started_at DESC);
CREATE INDEX IF NOT EXISTS idx_staff_presence_started ON balwyn_portal.staff_presence (started_at);

CREATE TABLE IF NOT EXISTS balwyn_portal.staff_ui_events (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id   uuid NOT NULL,
  account_key  text NOT NULL CHECK (char_length(account_key) BETWEEN 1 AND 254),
  actor_name   text NOT NULL CHECK (char_length(actor_name) BETWEEN 1 AND 200),
  kind         text NOT NULL CHECK (kind IN ('press')),
  label        text NOT NULL CHECK (char_length(label) BETWEEN 1 AND 120),
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_staff_ui_events_account ON balwyn_portal.staff_ui_events (account_key, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_staff_ui_events_created ON balwyn_portal.staff_ui_events (created_at);

ALTER TABLE balwyn_portal.staff_presence ENABLE ROW LEVEL SECURITY;
ALTER TABLE balwyn_portal.staff_ui_events ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS balwyn_server_access ON balwyn_portal.staff_presence;
DROP POLICY IF EXISTS balwyn_server_access ON balwyn_portal.staff_ui_events;
CREATE POLICY balwyn_server_access ON balwyn_portal.staff_presence TO balwyn_app USING (true) WITH CHECK (true);
CREATE POLICY balwyn_server_access ON balwyn_portal.staff_ui_events TO balwyn_app USING (true) WITH CHECK (true);
GRANT SELECT, INSERT, UPDATE, DELETE ON balwyn_portal.staff_presence TO balwyn_app;
GRANT SELECT, INSERT, DELETE ON balwyn_portal.staff_ui_events TO balwyn_app;
